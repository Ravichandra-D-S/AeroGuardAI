export function getAircraftById(id: string): Aircraft | undefined {
  return aircraft.find((a) => a.id === id);
}

export function getAircraftTrend(id: string): TrendPoint[] {
  const ac = getAircraftById(id);
  const base = ac?.temperature ?? 75;
  const points = ['Day 1', 'Day 2', 'Day 3', 'Day 4', 'Day 5', 'Day 6', 'Day 7'];
  const seed = id.charCodeAt(id.length - 1) % 5;
  return points.map((day, i) => ({
    day,
    value: Math.round((base + Math.sin(i + seed) * 6 + (i - 3) * 1.5) * 10) / 10,
  }));
}

